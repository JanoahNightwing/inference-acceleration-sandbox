import { useEffect, useRef, useState } from "react";

const DESCRIBE = {
  prompt: "Prompt",
  draft: "Draft guess, waiting for the target model",
  accepted: "Draft guess accepted by the target model",
  rejected: "Draft guess rejected",
  discarded: "Discarded: drafted after a rejected guess",
  target: "Generated by the target model",
};

function detail(t) {
  if (!t) return null;
  const parts = [DESCRIBE[t.kind]];
  if (t.kind === "target") {
    parts[0] = t.source === "bonus"
      ? "Bonus token from the target model (all drafts accepted)"
      : t.source === "resample" ? "Target model's replacement for a rejected guess" : DESCRIBE.target;
  }
  if (t.step !== undefined) parts.push(`step ${t.step + 1}`);
  if (t.q !== undefined && t.q !== null) parts.push(`draft prob q = ${t.q.toFixed(3)}`);
  if (t.p !== undefined && t.p !== null) parts.push(`target prob p = ${t.p.toFixed(3)}`);
  return parts.join(", ");
}

export default function TokenStream({ tokens, phase }) {
  const box = useRef(null);
  const [hover, setHover] = useState(null);

  useEffect(() => {
    const el = box.current;
    if (el && el.scrollHeight - el.scrollTop - el.clientHeight < 160) el.scrollTop = el.scrollHeight;
  }, [tokens]);

  const hovered = hover && tokens.find((t) => t.key === hover);

  return (
    <section className="stream">
      <div className="stream__text" ref={box} aria-live="off">
        {tokens.length === 0 && (
          <p className="stream__empty">
            Write a prompt and press Generate. The draft model's guesses appear in blue, then the target model
            checks them in one pass.
          </p>
        )}
        {tokens.map((t) => (
          <span
            key={t.key}
            className={[
              "tok", `tok--${t.kind}`,
              t.scanning && "is-scanning", t.leaving && "is-leaving", t.replaced && "is-replacement",
            ].filter(Boolean).join(" ")}
            onMouseEnter={() => setHover(t.key)}
            onMouseLeave={() => setHover((h) => (h === t.key ? null : h))}
          >
            {t.text}
          </span>
        ))}
        {phase === "running" && <span className="caret" aria-hidden="true" />}
      </div>
      <footer className="stream__foot">
        {hovered ? (
          <p className="inspect">{detail(hovered)}</p>
        ) : (
          <ul className="legend">
            <li><i className="sw sw--draft" />Draft guess</li>
            <li><i className="sw sw--accepted" />Accepted</li>
            <li><i className="sw sw--rejected" />Rejected</li>
            <li><i className="sw sw--target" />Target model</li>
            <li className="legend__hint">Hover a token for p and q</li>
          </ul>
        )}
      </footer>
    </section>
  );
}
