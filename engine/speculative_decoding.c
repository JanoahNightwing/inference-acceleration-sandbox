typedef struct {
    int *tokens;
    int length;
} SDTokens;

// ----------------------------------------------------------------------------
// event stream: with `-j 1`, every speculative step is emitted as one JSON line
// on stdout (draft guesses, per-token verification with p/q, timings) instead
// of the colored terminal output. Consumed by the Inference Acceleration Sandbox.

static int g_json = 0;            // 1 = emit JSONL events instead of colored text
static Tokenizer *g_tok = NULL;   // tokenizer used to decode token pieces in events

static double now_us() {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec * 1e6 + ts.tv_nsec / 1e3;
}

static void json_str(const char *s) {
    putchar('"');
    for (const unsigned char *c = (const unsigned char *)s; *c; c++) {
        switch (*c) {
            case '"':  fputs("\\\"", stdout); break;
            case '\\': fputs("\\\\", stdout); break;
            case '\n': fputs("\\n", stdout); break;
            case '\r': fputs("\\r", stdout); break;
            case '\t': fputs("\\t", stdout); break;
            default:
                if (*c < 0x20) { printf("\\u%04x", *c); }
                else { putchar(*c); }
        }
    }
    putchar('"');
}

// decoded text of `token` (given the previous token), with unprintable raw bytes dropped
static void json_piece(int prev_token, int token) {
    char *piece = decode(g_tok, prev_token, token);
    if (piece == NULL || token == 1) { json_str(""); return; }
    if (piece[0] != '\0' && piece[1] == '\0') {
        unsigned char b = piece[0];
        if (!(isprint(b) || isspace(b))) { json_str(""); return; }
    }
    json_str(piece);
}

static void json_config(const char *name, Config *c) {
    printf("\"%s\":{\"dim\":%d,\"hidden_dim\":%d,\"n_layers\":%d,\"n_heads\":%d,\"n_kv_heads\":%d,\"vocab_size\":%d,\"seq_len\":%d}",
           name, c->dim, c->hidden_dim, c->n_layers, c->n_heads, c->n_kv_heads, c->vocab_size, c->seq_len);
}

